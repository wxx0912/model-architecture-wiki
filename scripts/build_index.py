#!/usr/bin/env python3
"""Build a deterministic metadata index for Agent retrieval."""
from __future__ import annotations

import argparse
from pathlib import Path

from wiki_utils import ROOT, page_records


def render() -> str:
    groups = {"paradigm": [], "component": [], "model": [], "check": []}
    for path, meta, _ in page_records():
        groups.setdefault(str(meta.get("type")), []).append((str(meta.get("id")), str(meta.get("title")), path.relative_to(ROOT)))
    lines = ["# Generated Page Index", "", "> Generated by `python3 scripts/build_index.py`; do not edit manually.", ""]
    for kind in ("paradigm", "component", "model", "check"):
        lines.append(f"## {kind.title()}s")
        lines.append("")
        for page_id, title, path in sorted(groups[kind]):
            lines.append(f"- `{page_id}` — [{title}]({path.as_posix()})")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the generated file is stale")
    args = parser.parse_args()
    target = ROOT / "index.generated.md"
    content = render()
    if args.check:
        return 0 if target.exists() and target.read_text(encoding="utf-8") == content else 1
    target.write_text(content, encoding="utf-8")
    print(f"wrote {target.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
